import asyncio, pathlib, tempfile, os
ROOT = pathlib.Path(__file__).resolve().parent.parent
TMP = pathlib.Path(tempfile.mkdtemp())
from playwright.async_api import async_playwright
html = (ROOT/'game'/'pocket-warbands.html').read_text()
hook = 'window.__t={get state(){return state},get OP(){return OP},get B(){return B},get sheetKind(){return sheetKind},closeSheet,get meta(){return meta},runMods};})();\n</script>'
(TMP/'page.html').write_text('<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"></head><body>'+html.replace('})();\n</script>',hook)+'</body></html>')
D=str(ROOT/'tools'/'shots')+'/'; os.makedirs(D, exist_ok=True)
async def main():
    async with async_playwright() as p:
        b = await (p.chromium.launch(executable_path=os.environ['CHROME']) if os.environ.get('CHROME') else p.chromium.launch())
        pg = await b.new_page(viewport={'width':400,'height':860}, device_scale_factor=2)
        errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
        log = lambda *a: print(*a, flush=True)
        await pg.goto((TMP/'page.html').as_uri()); await pg.wait_for_timeout(900)
        await pg.screenshot(path=D+'01title.png')
        await pg.click('.galentry'); await pg.wait_for_timeout(900)
        await pg.screenshot(path=D+'02galaxy-live.png')
        await pg.click('[data-act=galback]'); await pg.wait_for_timeout(500)
        # win via lab
        log('after back', await pg.evaluate("__t.state.screen"))
        log('sheet', await pg.evaluate("__t.sheetKind"))
        if await pg.locator('.scrim.open [data-act=boon]').count(): await pg.click('.scrim.open [data-act=boon] >> nth=0'); await pg.wait_for_timeout(500)
        if await pg.locator('[data-act=coachskip]').first.is_visible(): await pg.click('[data-act=coachskip]')
        await pg.screenshot(path=D+'02b-camp.png')
        await pg.click('[data-act=lab] >> nth=0'); await pg.wait_for_timeout(300)
        await pg.click('.scrim [data-act=labwin]'); await pg.wait_for_timeout(900)
        await pg.screenshot(path=D+'03end.png', full_page=True)
        log('galaxy', await pg.evaluate("JSON.stringify(__t.meta.galaxy)"))
        await pg.click('[data-act=legend] >> nth=0'); await pg.wait_for_timeout(400)
        await pg.click('[data-act=newgame]'); await pg.wait_for_timeout(900)
        await pg.click('[data-act=galsel][data-k=hive]'); await pg.wait_for_timeout(300)
        await pg.click('[data-act=galthreat][data-v="1"]'); await pg.wait_for_timeout(200)
        await pg.click('[data-act=galdoc][data-v=merc]'); await pg.wait_for_timeout(300)
        await pg.screenshot(path=D+'04galaxy-pick.png', full_page=True)
        await pg.keyboard.press('Space'); await pg.wait_for_timeout(1200)
        log('run', await pg.evaluate("JSON.stringify(__t.state.run)"), 'gold', await pg.evaluate("__t.state.gold"), 'morale', await pg.evaluate("__t.state.maxMorale"), 'roster', await pg.evaluate("__t.state.roster.map(u=>u.cls+u.level).join(',')"), 'foes', await pg.evaluate("__t.state.enemy && __t.state.enemy.units.length"))
        if await pg.locator('.scrim.open [data-act=boon]').count(): await pg.click('.scrim.open [data-act=boon] >> nth=0'); await pg.wait_for_timeout(500)
        if await pg.locator('[data-act=coachskip]').first.is_visible(): await pg.click('[data-act=coachskip]')
        await pg.screenshot(path=D+'05camp-hive.png')
        # lab: liberate all, threat, fight Architect
        await pg.click('[data-act=lab] >> nth=0'); await pg.wait_for_timeout(300)
        await pg.click('.scrim [data-act=labgalall]'); await pg.wait_for_timeout(200)
        await pg.click('.scrim [data-act=labthreat]'); await pg.wait_for_timeout(200)
        await pg.click('.scrim [data-act=lablevel][data-v="5"]'); await pg.wait_for_timeout(200)
        await pg.click('.scrim [data-act=labarch]'); await pg.wait_for_timeout(800)
        log('boss enemy', await pg.evaluate("__t.state.enemy.units[0].boss"), await pg.evaluate("__t.state.battle"))
        await pg.screenshot(path=D+'06camp-arch.png')
        await pg.evaluate("__t.closeSheet()")
        await pg.click('#bar .fab'); await pg.wait_for_timeout(500)
        if await pg.evaluate("__t.sheetKind"): await pg.click('.scrim [data-act=close] >> nth=-1'); await pg.wait_for_timeout(300); await pg.click('#bar .fab')
        await pg.wait_for_timeout(600)
        await pg.evaluate("__t.B.fs.filter(f=>!f.side).forEach(f=>{f.maxHp*=25; f.hp=f.maxHp; f.ghost=f.hp;})")
        for i,tm in enumerate([3000]+[1500]*10):
            await pg.wait_for_timeout(tm)
            for _ in range(20):
                if await pg.evaluate("!!(__t.B && (__t.B.beamWarn || __t.B.beam))"): break
                await pg.wait_for_timeout(100)
            await pg.screenshot(path=D+f'07battle{i}.png')
            log('t', await pg.evaluate("__t.B && Math.round(__t.B.t)"), 'warn', await pg.evaluate("__t.B && !!__t.B.beamWarn"), 'beam', await pg.evaluate("__t.B && !!__t.B.beam"), 'bosshp', await pg.evaluate("(()=>{const f=__t.B&&__t.B.fs.find(x=>x.bossK); return f? Math.round(100*f.hp/f.maxHp)+'% imm '+(f.immune||0).toFixed(1):'' })()"))
        await pg.evaluate("(()=>{const f=__t.B.fs.find(x=>x.bossK); f.hp=f.maxHp*0.6;})()"); await pg.wait_for_timeout(400)
        log('phase', await pg.evaluate("(()=>{const f=__t.B.fs.find(x=>x.bossK); return [f.immune.toFixed(1), __t.B.fs.filter(o=>o.name==='Construct').length]})()"))
        await pg.screenshot(path=D+'07phase.png')
        if await pg.locator('[data-act=skip]').count(): await pg.click('[data-act=skip]')
        await pg.wait_for_timeout(1500)
        log('result', await pg.evaluate("__t.state.results && __t.state.results.win"))
        await pg.screenshot(path=D+'08result.png')
        # galaxy all liberated view
        await pg.evaluate("__t.closeSheet()")
        await pg.goto((TMP/'page.html').as_uri()); await pg.wait_for_timeout(700)
        await pg.click('.galentry'); await pg.wait_for_timeout(500)
        await pg.click('[data-act=galsel][data-k=core]'); await pg.wait_for_timeout(600)
        await pg.screenshot(path=D+'09galaxy-core.png')
        await pg.click('.labentry') if await pg.locator('.labentry').count() else None
        print('ERRORS', errs)
        await b.close()
asyncio.run(main())
