import asyncio, pathlib, tempfile, os
ROOT = pathlib.Path(__file__).resolve().parent.parent
TMP = pathlib.Path(tempfile.mkdtemp())
CHROME = os.environ.get('CHROME')  # optional path to a Chromium binary
from playwright.async_api import async_playwright
html = (ROOT/'game'/'pocket-warbands.html').read_text()
hook = 'window.__t={get state(){return state},get OP(){return OP},get B(){return B},get sheetKind(){return sheetKind},closeSheet,meta};})();\n</script>'
assert '})();\n</script>' in html
(TMP/'page.html').write_text('<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"></head><body>'+html.replace('})();\n</script>',hook)+'</body></html>')
D=str(ROOT/'tools'/'shots')+'/'; os.makedirs(D, exist_ok=True)
async def main():
    async with async_playwright() as p:
        b = await (p.chromium.launch(executable_path=CHROME) if CHROME else p.chromium.launch())
        pg = await b.new_page(viewport={'width':400,'height':860}, device_scale_factor=2)
        errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
        log = lambda *a: print(*a, flush=True)
        await pg.goto((TMP/'page.html').as_uri()); await pg.wait_for_timeout(900)
        await pg.click('[data-act=play]'); await pg.wait_for_timeout(600)
        if await pg.locator('[data-act=boon]').count(): await pg.click('[data-act=boon] >> nth=0'); await pg.wait_for_timeout(600)
        if await pg.locator('[data-act=coachskip]').count(): await pg.click('[data-act=coachskip]')
        await pg.evaluate("__t.state.screen='title'; render()") if False else None
        # back to title via evaluate-free route: reload page (title shows on load?)
        await pg.reload(); await pg.wait_for_timeout(900)
        log('screen after reload', await pg.evaluate("__t.state.screen"))
        await pg.locator('.labentry').scroll_into_view_if_needed(); await pg.screenshot(path=D+'01title.png')
        await pg.click('.labentry'); await pg.wait_for_timeout(500)
        await pg.screenshot(path=D+'02lab.png')
        for act in ['labcash','labheal','labstash','labmythic','lablegend','labpromote']:
            g0 = await pg.evaluate("__t.state.gold")
            await pg.click(f'.scrim [data-act={act}]'); await pg.wait_for_timeout(250)
            log(act, 'gold', g0, '->', await pg.evaluate("__t.state.gold"), 'sheet', await pg.evaluate("__t.sheetKind"))
        await pg.click('.scrim [data-act=lablevel][data-v="7"]'); await pg.wait_for_timeout(250)
        log('levels', await pg.evaluate("__t.state.roster.map(u=>u.level+'/'+u.pending).join(' ')"))
        await pg.click('.scrim [data-act=labsector][data-v="2"]'); await pg.wait_for_timeout(700)
        log('sector', await pg.evaluate("__t.state.battle"), await pg.evaluate("__t.state.screen"))
        await pg.screenshot(path=D+'03sector2.png')
        # open lab again via settings
        
        await pg.click('[data-act=settings] >> nth=0'); await pg.wait_for_timeout(400)
        await pg.screenshot(path=D+'04settings.png', full_page=False)
        await pg.click('.scrim [data-act=lab]'); await pg.wait_for_timeout(400)
        await pg.click('.scrim [data-act=labboss][data-v="3"]'); await pg.wait_for_timeout(700)
        log('boss', await pg.evaluate("__t.state.battle"), await pg.evaluate("JSON.stringify(__t.state.node)"))
        await pg.screenshot(path=D+'05boss.png')
        # settings: rings, big, hc
        await pg.click('[data-act=settings] >> nth=0'); await pg.wait_for_timeout(300)
        await pg.click('.scrim [data-act=setbig]'); await pg.wait_for_timeout(200)
        await pg.click('.scrim [data-act=sethc]'); await pg.wait_for_timeout(200)
        await pg.screenshot(path=D+'06settings-big.png')
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(400)
        await pg.screenshot(path=D+'07camp-big.png')
        # deploy with keyboard
        await pg.keyboard.press('Space'); await pg.wait_for_timeout(2600)
        log('after space', await pg.evaluate("__t.state.screen"))
        log('sheet', await pg.evaluate("__t.sheetKind"))
        await pg.screenshot(path=D+'07b-space.png')
        for i in range(3):
            if await pg.evaluate("__t.state.screen")!='camp': break
            if await pg.evaluate("__t.sheetKind"): await pg.click('.scrim [data-act=close] >> nth=-1'); await pg.wait_for_timeout(400)
            await pg.keyboard.press('Space'); await pg.wait_for_timeout(2600)
        log('screen', await pg.evaluate("__t.state.screen"))
        await pg.keyboard.press('1'); await pg.wait_for_timeout(200)
        log('aim', await pg.evaluate("__t.B && __t.B.aim"))
        await pg.screenshot(path=D+'08battle.png')
        box = await pg.locator('#field').bounding_box()
        await pg.mouse.click(box['x']+box['width']*0.7, box['y']+box['height']*0.5); await pg.wait_for_timeout(1500)
        await pg.screenshot(path=D+'09battle2.png')
        await pg.keyboard.press('s'); await pg.wait_for_timeout(2500)
        log('after skip', await pg.evaluate("__t.state.screen"))
        await pg.screenshot(path=D+'10results.png')
        await pg.mouse.click(200, 300); await pg.wait_for_timeout(600)
        await pg.keyboard.press('Space'); await pg.wait_for_timeout(800)
        log('after results space', await pg.evaluate("__t.state.screen"), await pg.evaluate("__t.sheetKind"))
        await pg.screenshot(path=D+'11after.png')
        await pg.evaluate("__t.closeSheet()"); await pg.wait_for_timeout(500)
        await pg.click('[data-act=camp] >> nth=-1'); await pg.wait_for_timeout(900)
        await pg.screenshot(path=D+'11b-camp.png')
        # galleries
        await pg.click('[data-act=settings] >> nth=0'); await pg.wait_for_timeout(300)
        await pg.click('.scrim [data-act=setbig]'); await pg.click('.scrim [data-act=sethc]')
        await pg.click('.scrim [data-act=lab]'); await pg.wait_for_timeout(300)
        await pg.click('.scrim [data-act=labgallery]'); await pg.wait_for_timeout(500)
        for k in ['jets','laser','halo','arcs','phoenix']:
            await pg.click(f'.scrim [data-act=labfx][data-k={k}]'); await pg.wait_for_timeout(80)
        await pg.click('.scrim [data-act=labtier][data-v=legendary]'); await pg.click('.scrim [data-act=labpaint][data-v="3"]'); await pg.click('.scrim [data-act=labvisor][data-v="2"]')
        await pg.wait_for_timeout(700); await pg.screenshot(path=D+'12gallery.png')
        await pg.click('.scrim [data-act=lab] >> nth=-1'); await pg.wait_for_timeout(300)
        await pg.click('.scrim [data-act=labbosses]'); await pg.wait_for_timeout(1500)
        await pg.screenshot(path=D+'13bosses.png')
        await pg.click('.scrim [data-act=lab]'); await pg.wait_for_timeout(300)
        await pg.click('.scrim [data-act=labwave][data-v="6"]'); await pg.wait_for_timeout(500)
        await pg.click('.scrim [data-act=ophero][data-id=oracle]'); await pg.wait_for_timeout(800)
        log('outpost', await pg.evaluate("[__t.OP.wave, __t.OP.credits, __t.OP.phase]"))
        await pg.keyboard.press('Space'); await pg.wait_for_timeout(2500)
        log('outpost phase', await pg.evaluate("__t.OP.phase"))
        await pg.keyboard.press('f'); await pg.keyboard.press('2'); await pg.wait_for_timeout(1200)
        log('speed', await pg.evaluate("__t.OP.speed"))
        await pg.screenshot(path=D+'14outpost.png')
        print('ERRORS', errs)
        await b.close()
asyncio.run(main())
