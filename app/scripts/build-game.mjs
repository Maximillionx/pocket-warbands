// Wraps the published game page in a full document and writes game-html.ts.
// Usage: node scripts/build-game.mjs path/to/pocket-warbands.html
import { readFileSync, writeFileSync } from 'node:fs';
const src = process.argv[2] || 'pocket-warbands.html';
const body = readFileSync(src, 'utf8');
const doc = '<!doctype html><html><head><meta charset="utf-8">'
  + '<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover">'
  + '<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}'
  + 'html,body{margin:0;background:#0b1020;overscroll-behavior:none;-webkit-text-size-adjust:100%}'
  + 'body{font:14px system-ui;-webkit-user-select:none;user-select:none}input{-webkit-user-select:text;user-select:text}'
  + 'img{max-width:100%}[hidden]{display:none!important}</style></head><body>'
  + body + '</body></html>';
writeFileSync('game-html.ts', '// Generated by scripts/build-game.mjs. Do not edit by hand.\nconst GAME_HTML: string = ' + JSON.stringify(doc) + ';\nexport default GAME_HTML;\n');
console.log(`game-html.ts written (${(doc.length/1024).toFixed(0)} KB)`);
